/* ---------- HERO WAVES ---------- */
const wave = $('#wave'), wx = wave.getContext('2d');
let heroOn = true, wt = 0, lv = 0;
function fit(c) {
  const r = c.getBoundingClientRect(), d = Math.min(2, devicePixelRatio || 1);
  if (c.width !== Math.round(r.width * d) || c.height !== Math.round(r.height * d)) { c.width = Math.round(r.width * d); c.height = Math.round(r.height * d); }
  return d;
}
function drawWave() {
  const d = fit(wave), w = wave.width, h = wave.height;
  wx.clearRect(0, 0, w, h);
  lv += (P.level - lv) * 0.08;
  [['#8B5CF6', 0.55, 1], ['#2DD4BF', 0.45, 1.6], ['#C4F25B', 0.5, 2.3], ['#F472B6', 0.25, 3.1]].forEach(([c, al, sp], i) => {
    wx.beginPath(); wx.strokeStyle = c; wx.globalAlpha = al; wx.lineWidth = (2.2 - i * 0.3) * d;
    const amp = h * (0.12 + 0.05 * i) * (1 + lv * 1.6), base = h * (0.55 + 0.08 * i);
    for (let x = 0; x <= w; x += 8 * d) {
      const u = x / w, y = base + Math.sin(u * 6.5 * sp * 0.6 + wt * sp * 0.6 + i) * amp * Math.sin(u * Math.PI) + Math.sin(u * 14 + wt * 1.3 + i * 2) * amp * 0.25;
      x ? wx.lineTo(x, y) : wx.moveTo(x, y);
    }
    wx.stroke();
  });
  wx.globalAlpha = 1;
}
function waveLoop() { if (heroOn) { wt += 0.012 + lv * 0.04; drawWave(); } requestAnimationFrame(waveLoop); }
new IntersectionObserver((es) => { heroOn = es[0].isIntersecting; }).observe($('#hero'));
if (reduce) drawWave(); else waveLoop();
addEventListener('resize', () => { center(); if (SONGS.length) frame(); if (reduce) drawWave(); });

